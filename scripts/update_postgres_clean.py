import asyncio
import os
from dotenv import load_dotenv

load_dotenv('backend/.env')
db_url = os.getenv('DATABASE_URL')

async def update_pg():
    import asyncpg
    pg_url = db_url.replace('postgresql+asyncpg://', 'postgresql://')
    conn = await asyncpg.connect(pg_url)
    
    # 1. Update Triage Alerts
    alerts = [
        (1, 'red', 'attendance', 'Chronic Absenteeism: 20 Students Absent Today', '5 students (including Kabir Mehta, Roll #15) have been absent for 3+ consecutive days without parent leave applications.', 5, 'Assign Class Teacher to Call Parents', '/api/admin/triage/1/act', False),
        (2, 'red', 'operations', 'Emergency Period Substitution: 3 Unassigned Periods', 'Mathematics faculty on emergency medical leave. Periods 2, 4 in Class 8B and Period 6 in Class 9A require immediate substitute assignment.', 3, 'Auto-Assign Available Free Period Faculty', '/api/admin/triage/2/act', False),
        (3, 'orange', 'fees', 'Fee Milestone 2 Overdue: ₹5,55,000 Pending', 'Fee Milestone 2 was due on 10th Oct. 30 student accounts across Class 8 and Class 9 are overdue past the grace period.', 30, 'Trigger Targeted WhatsApp & Call Reminders', '/api/admin/triage/3/act', False),
        (4, 'orange', 'finance', 'Monthly Faculty & Staff Payroll Batch Sign-Off', 'Monthly payroll batch for 42 staff members (Total: ₹18,40,000) generated by Accounts and awaiting Principal executive approval.', 42, 'Review & Authorize Payroll Batch', '/api/admin/triage/4/act', False),
        (5, 'red', 'escalations', 'HOD Academic Escalation: Unit Test 2 Gradebook Delayed', 'Prof. Rajeshwari Nair escalated Class 8B Mathematics gradebook submission. Teacher unresponsive past 48h deadline.', 35, 'Review Escalation & Intervene', '/api/admin/triage/5/act', False)
    ]
    
    await conn.execute('DELETE FROM triage_alerts')
    for a in alerts:
        await conn.execute('''
            INSERT INTO triage_alerts (id, level, category, title, description, count_affected, action_label, action_endpoint, resolved)
            VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
        ''', *a)

    # 2. Update Admin Tasks: Replace task 1 and task 6
    await conn.execute('''
        UPDATE admin_tasks 
        SET title = 'Authorize Monthly Faculty & Staff Payroll Batch',
            description = 'Review Accounts ledger reconciliation and release executive sign-off for ₹18,40,000 monthly faculty disbursement.',
            domain = 'finance',
            due_date = 'Today, 5:00 PM',
            is_escalated = false
        WHERE id = 1
    ''')

    await conn.execute('''
        UPDATE admin_tasks 
        SET title = 'Verify Emergency Period Substitution Log',
            description = 'Validate that 3 free periods created by medical leave are successfully covered by available proxy teachers.',
            domain = 'executive',
            due_date = 'Today, 3:30 PM'
        WHERE id = 6
    ''')
    
    # 3. Permanently delete any transport or inventory tasks
    await conn.execute("DELETE FROM admin_tasks WHERE domain IN ('transport', 'inventory')")

    rows = await conn.fetch('SELECT id, level, category, title FROM triage_alerts ORDER BY id')
    print('Updated PostgreSQL triage_alerts:')
    for r in rows:
        print(dict(r))
        
    tasks = await conn.fetch('SELECT id, title, domain FROM admin_tasks ORDER BY id')
    print('Updated PostgreSQL admin_tasks:')
    for t in tasks:
        print(dict(t))

    await conn.close()

if __name__ == '__main__':
    asyncio.run(update_pg())
